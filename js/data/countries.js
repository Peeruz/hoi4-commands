// 构建查询索引：输入任意（代码/英文/中文）-> 标准对象
(function () {
  const list = window.HOI4_COUNTRIES;
  const byTag = {};
  const byName = {}; // key 全小写
  list.forEach(function (c) {
    byTag[c.tag.toUpperCase()] = c;
    byName[c.en.toLowerCase()] = c;
    (c.zh || []).forEach(function (z) { byName[z.toLowerCase()] = c; });
  });
  window.HOI4_COUNTRY_INDEX = { byTag: byTag, byName: byName, list: list };
})();

// 解析国家：返回 {tag, country} 或 null
window.resolveCountry = function (text) {
  if (!text) return null;
  const t = String(text).trim();
  const up = t.toUpperCase();
  const idx = window.HOI4_COUNTRY_INDEX;
  if (idx.byTag[up]) return { tag: up, country: idx.byTag[up] };
  const low = t.toLowerCase();
  if (window.HOI4_TAG_ALIASES[low]) {
    const tag = window.HOI4_TAG_ALIASES[low];
    return { tag: tag, country: idx.byTag[tag] };
  }
  if (idx.byName[low]) return { tag: idx.byName[low].tag, country: idx.byName[low] };
  // 模糊：包含匹配中文
  for (const c of idx.list) {
    if (c.zh && c.zh.some((z) => t.includes(z))) return { tag: c.tag, country: c };
    if (t.toLowerCase().includes(c.en.toLowerCase())) return { tag: c.tag, country: c };
  }
  return null;
};
